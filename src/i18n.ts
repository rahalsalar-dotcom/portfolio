export const languages: Language[] = ['en', 'ar', 'ku']
export const rtlLanguages: Language[] = ['ar', 'ku']

export const languageMeta: Record<Language, { label: string; short: string; dir: 'ltr' | 'rtl' }> = {
  en: { label: languageNames.en, short: 'EN', dir: 'ltr' },
  ar: { label: languageNames.ar, short: 'AR', dir: 'rtl' },
  ku: { label: languageNames.ku, short: 'KU', dir: 'rtl' },
}

export function isLanguage(value: string | null): value is Language {
  return value === 'en' || value === 'ar' || value === 'ku'
}

export function localize(text: LocalizedText | string, language: Language): string {
  if (typeof text === 'string') {
    return text
  }

  return text[language] || text.en || Object.values(text)[0] || ''
}

export function emptyLocalizedText(value = ''): LocalizedText {
  return {
    en: value,
    ar: value,
    ku: value,
  }
}

